// Regenerates the SDK's typed layer from the live OpenAPI document:
//
//   node scripts/generate.mjs                                      # https://rsflowhub.com/api/v1/openapi.json
//   node scripts/generate.mjs http://localhost/api/v1/openapi.json
//   node scripts/generate.mjs path/to/openapi.json
//
// Writes (never edit these by hand):
//   src/generated/operations.ts   resource -> method -> [HTTP method, path]
//   src/generated/types.ts        typed params + resource interfaces (autocomplete)
//   docs/ENDPOINTS.md             reference table of every method
//
// The SDK works without running this (see src/operations.ts); it only adds
// types and docs. The "Sync with API" GitHub workflow runs it weekly.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] ?? process.env.RSFLOWHUB_SPEC_URL ?? 'https://rsflowhub.com/api/v1/openapi.json';

let spec;
try {
  const raw = /^https?:\/\//.test(source)
    ? await (await fetch(source, { headers: { Accept: 'application/json', 'User-Agent': 'rsflowhub-node-generator' } })).text()
    : await readFile(source, 'utf8');
  spec = JSON.parse(raw);
} catch (error) {
  console.error(`Could not read the OpenAPI document from ${source}: ${error.message}`);
  process.exit(1);
}
if (!spec?.openapi || !spec?.paths) {
  console.error(`${source} is not an OpenAPI document.`);
  process.exit(1);
}

/** @type {Record<string, Record<string, {http: string, path: string, op: any}>>} */
const ops = {};
for (const [path, operations] of Object.entries(spec.paths)) {
  for (const [http, op] of Object.entries(operations)) {
    const sdk = op?.['x-rsflowhub-sdk'];
    if (sdk?.resource && sdk?.method) (ops[sdk.resource] ??= {})[sdk.method] = { http: http.toUpperCase(), path, op };
  }
}
const resources = Object.keys(ops).sort();
if (!resources.length) {
  console.error('No operations with x-rsflowhub-sdk found.');
  process.exit(1);
}
const sorted = (o) => Object.keys(o).sort();
const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const ident = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s));
const comment = (s) => String(s).replace(/\*\//g, '*\\/');
const HEADER = '// Generated by scripts/generate.mjs from the RSFlowHub OpenAPI document. Do not edit.\n';

// 1. Operation map -----------------------------------------------------------
let out = HEADER + '\nimport type { OperationMap } from \'../operations.js\';\n\nexport const operations: OperationMap = {\n';
for (const r of resources) {
  out += `  ${ident(r)}: {\n`;
  for (const m of sorted(ops[r])) out += `    ${ident(m)}: ['${ops[r][m].http}', '${ops[r][m].path}'],\n`;
  out += '  },\n';
}
out += '};\n';
await writeFile(`${root}/src/generated/operations.ts`, out);

// 2. Types --------------------------------------------------------------------
function tsType(schema = {}, indent = '  ') {
  let t;
  if (schema.format === 'binary') t = 'Blob | Uint8Array';
  else if (Array.isArray(schema.enum) && schema.enum.length) t = schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  else if (schema.type === 'string') t = 'string';
  else if (schema.type === 'integer' || schema.type === 'number') t = 'number';
  else if (schema.type === 'boolean') t = 'boolean';
  else if (schema.type === 'array') {
    const item = tsType(schema.items ?? {}, indent);
    t = /[|&{]/.test(item) ? `Array<${item}>` : `${item}[]`;
  } else if (schema.type === 'object' && schema.properties && Object.keys(schema.properties).length) t = objectType(schema, indent);
  else if (schema.type === 'object') t = 'Record<string, unknown>';
  else t = 'unknown';
  return schema.nullable ? `${t} | null` : t;
}

function docFor(schema = {}) {
  const parts = [];
  if (schema.description) parts.push(schema.description);
  if (schema.maxLength !== undefined) parts.push(`Max ${schema.maxLength} characters.`);
  if (schema.minLength !== undefined) parts.push(`Min ${schema.minLength} characters.`);
  if (schema.maxItems !== undefined) parts.push(`Max ${schema.maxItems} items.`);
  if (schema.minItems !== undefined) parts.push(`Min ${schema.minItems} items.`);
  if (schema.minimum !== undefined || schema.maximum !== undefined) parts.push(`Range ${schema.minimum ?? '…'} to ${schema.maximum ?? '…'}.`);
  if (schema.format && schema.format !== 'binary') parts.push(`Format: ${schema.format}.`);
  return parts.length ? comment(parts.join(' ')) : '';
}

function objectType(schema, indent) {
  const required = new Set(schema.required ?? []);
  const inner = indent + '  ';
  let s = '{\n';
  for (const [name, prop] of Object.entries(schema.properties)) {
    const doc = docFor(prop);
    if (doc) s += `${inner}/** ${doc} */\n`;
    s += `${inner}${ident(name)}${required.has(name) ? '' : '?'}: ${tsType(prop, inner)};\n`;
  }
  return s + indent + '}';
}

function bodyOrQuerySchema(op) {
  const content = op.requestBody?.content;
  if (content) return Object.values(content)[0]?.schema ?? null;
  const query = (op.parameters ?? []).filter((p) => p.in === 'query');
  if (!query.length) return null;
  return {
    type: 'object',
    properties: Object.fromEntries(query.map((p) => [p.name, p.schema ?? {}])),
    required: query.filter((p) => p.required).map((p) => p.name),
  };
}

let types = HEADER + `
import type { RSFlowHubResponse } from '../response.js';
import type { RequestOptions } from '../transport.js';

/** A path id: number or string. */
export type Id = string | number;

/** Any method name works at runtime, including ones newer than this SDK. */
export interface DynamicResource {
  [method: string]: (...args: any[]) => Promise<RSFlowHubResponse>;
}
`;

const titles = {};
for (const r of resources) {
  const methods = sorted(ops[r]);
  titles[r] = ops[r][methods[0]].op.tags?.[0] ?? pascal(r);
  let iface = `\n/** ${comment(titles[r])}: \`client.${r}\`. */\nexport interface ${pascal(r)}Resource extends DynamicResource {\n`;

  for (const m of methods) {
    const { http, path, op } = ops[r][m];
    const schema = bodyOrQuerySchema(op);
    const paramsName = `${pascal(r)}${pascal(m)}Params`;
    const args = (op.parameters ?? []).filter((p) => p.in === 'path').map((p) => `${p.name.replace(/_(\w)/g, (_, c) => c.toUpperCase())}: Id`);

    if (schema && Object.keys(schema.properties ?? {}).length) {
      types += `\n/** Parameters of \`client.${r}.${m}()\`. */\nexport interface ${paramsName} ${objectType(schema, '')}\n`;
      args.push(`params${schema.required?.length ? '' : '?'}: ${paramsName}`);
    }
    args.push('options?: RequestOptions');

    const credits = op['x-rsflowhub-credits'];
    const doc = [
      op.summary,
      op.description,
      `\`${http} ${path}\`${credits ? `, from ${credits.base_credits} credit${credits.base_credits === 1 ? '' : 's'}` : ''}.`,
    ].filter(Boolean).map(comment);
    iface += `  /**\n${doc.map((d) => `   * ${d}`).join('\n   *\n')}\n   */\n  ${ident(m)}(${args.join(', ')}): Promise<RSFlowHubResponse>;\n`;
  }
  types += iface + '}\n';
}

types += `\n/** Every resource on the client. */\nexport interface Resources {\n`;
for (const r of resources) types += `  ${ident(r)}: ${pascal(r)}Resource;\n`;
types += '}\n';
await writeFile(`${root}/src/generated/types.ts`, types);

// 3. Reference docs -----------------------------------------------------------
const md = ['# RSFlowHub JavaScript / TypeScript SDK: method reference', '', 'Generated by `scripts/generate.mjs` from the [RSFlowHub OpenAPI document](https://rsflowhub.com/api/v1/openapi.json). Do not edit.', ''];
for (const r of resources) {
  md.push(`## \`client.${r}\`: ${titles[r]}`, '', '| Method | HTTP | Description | Credits |', '| --- | --- | --- | --- |');
  for (const m of sorted(ops[r])) {
    const { http, path, op } = ops[r][m];
    const desc = String(op.description ?? op.summary ?? '').replace(/\|/g, '\\|');
    const credits = op['x-rsflowhub-credits']?.base_credits;
    md.push(`| \`${m}()\` | \`${http} ${path}\` | ${desc} | ${credits === undefined ? '-' : `from ${credits}`} |`);
  }
  md.push('');
}
await mkdir(`${root}/docs`, { recursive: true });
await writeFile(`${root}/docs/ENDPOINTS.md`, md.join('\n'));

const count = resources.reduce((n, r) => n + Object.keys(ops[r]).length, 0);
console.log(`Generated ${count} methods in ${resources.length} resources from ${source}`);
